#!/usr/bin/env python3
"""
scripts/sync_calculator_counts.py — Master Calculator Metric & Count Synchronizer

Establishes a single master source of truth for:
- solvers_count: Total active deterministic calculation engines in CALCULATOR_REGISTRY (e.g. 428)
- mcp_tools_count: Total MCP tools exposed via JSON-RPC 2.0 (solvers_count + 1 legacy alias = 429)
- calculators_count: Total individual calculator HTML pages deployed on the site (e.g. 438)
- categories_count: Total active domain disciplines (e.g. 15)
- sitemap_urls_count: Total canonical URLs in sitemap.xml (e.g. 460)

Updates:
1. config/metrics.json and config/metrics.js (Single Source of Truth)
2. mcp/index.html (Title count, domain breakdown grid, and tool count badges)
3. mcp/server.js (Dynamic catalog resource solvers_count)
4. mcp/schemas.json (Full machine-readable schemas for all MCP tools)
5. functions/api/v1/mcp.js (Description strings and tool metadata)
6. api/v1/openapi.json (OpenAPI description strings)
7. index.html (Homepage MCP card description)
"""

import os
import sys
import json
import glob
import re
from pathlib import Path
from datetime import datetime, timezone
from collections import Counter

REPO_ROOT = Path(__file__).resolve().parent.parent

def calculate_metrics():
    """Computes all site counts dynamically from canonical sources."""
    # 1. Registry solvers
    registry_json_path = REPO_ROOT / "api" / "solvers" / "calculator_registry.json"
    if not registry_json_path.exists():
        raise FileNotFoundError(f"Missing registry at {registry_json_path}")
    
    with open(registry_json_path, "r", encoding="utf-8") as f:
        registry = json.load(f)
    
    solvers_count = len(registry)
    mcp_tools_count = solvers_count + 1  # Includes legacy omni_octagon_solver alias

    # Category breakdown from registry
    cat_counter = Counter(calc.get("category", "general") for calc in registry.values())
    category_breakdown = dict(cat_counter.most_common())
    categories_count = len(category_breakdown)

    # 2. Filesystem HTML calculator pages
    all_html = glob.glob(str(REPO_ROOT / "**/*.html"), recursive=True)
    calc_pages = []
    hub_pages = []
    meta_pages = []

    for path_str in all_html:
        rel = os.path.relpath(path_str, REPO_ROOT)
        if any(rel.startswith(x) for x in ['api/', 'mcp/', 'pricing/', 'embed/']) or rel in ['index.html', '404.html']:
            meta_pages.append(rel)
        elif rel.count('/') == 1 and rel.endswith('index.html'):
            hub_pages.append(rel)
        elif rel.startswith('geometry/') and rel.count('/') <= 3 and rel.endswith('index.html') and any(rel == f'geometry/{x}/index.html' for x in ['2d', '3d', '2d/shapes']):
            hub_pages.append(rel)
        else:
            calc_pages.append(rel)

    calculators_count = len(calc_pages)
    total_html_pages = len(all_html)

    # 3. Sitemap URL count
    sitemap_path = REPO_ROOT / "sitemap.xml"
    sitemap_urls_count = 0
    if sitemap_path.exists():
        with open(sitemap_path, "r", encoding="utf-8") as f:
            sitemap_content = f.read()
            sitemap_urls_count = sitemap_content.count("<loc>")

    metrics = {
        "solvers_count": solvers_count,
        "mcp_tools_count": mcp_tools_count,
        "calculators_count": calculators_count,
        "categories_count": categories_count,
        "total_html_pages": total_html_pages,
        "sitemap_urls_count": sitemap_urls_count,
        "supported_languages": ["en", "es", "fr", "de", "it", "pt", "nl", "pl", "sv", "no", "fi", "ro"],
        "category_breakdown": category_breakdown,
        "last_updated": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    }

    return metrics, registry

def write_metrics_files(metrics):
    """Writes config/metrics.json and config/metrics.js."""
    config_dir = REPO_ROOT / "config"
    config_dir.mkdir(parents=True, exist_ok=True)

    json_path = config_dir / "metrics.json"
    with open(json_path, "w", encoding="utf-8") as f:
        json.dump(metrics, f, indent=2)
    print(f"✅ Saved master metrics: {json_path}")

    js_path = config_dir / "metrics.js"
    js_content = f"""/**
 * config/metrics.js — Master Site Metrics & Inventory Values
 * Automatically generated by scripts/sync_calculator_counts.py
 */

export const METRICS = {json.dumps(metrics, indent=2)};

export const SOLVERS_COUNT = {metrics['solvers_count']};
export const MCP_TOOLS_COUNT = {metrics['mcp_tools_count']};
export const CALCULATORS_COUNT = {metrics['calculators_count']};
export const CATEGORIES_COUNT = {metrics['categories_count']};
"""
    with open(js_path, "w", encoding="utf-8") as f:
        f.write(js_content)
    print(f"✅ Saved JS master metrics: {js_path}")

def sync_mcp_page(metrics):
    """Updates mcp/index.html with master solver count and rich domain breakdown."""
    mcp_html_path = REPO_ROOT / "mcp" / "index.html"
    if not mcp_html_path.exists():
        print(f"⚠️ mcp/index.html not found at {mcp_html_path}")
        return

    content = mcp_html_path.read_text(encoding="utf-8")
    solvers = metrics["solvers_count"]
    cats = metrics["categories_count"]
    breakdown = metrics["category_breakdown"]

    # 1. Update the heading
    heading_pattern = re.compile(r'<h2[^>]*>🛠️ Active Deterministic Tools[^<]*</h2>')
    new_heading = f'<h2 style="font-size: 1.5rem; margin-bottom: 0.5rem;">🛠️ Active Deterministic Tools ({solvers} Solvers across {cats} Disciplines)</h2>'
    if heading_pattern.search(content):
        content = heading_pattern.sub(new_heading, content)
    else:
        print("  ⚠️ Heading pattern not matched in mcp/index.html")

    # 2. Build Category Breakdown Badges
    cat_badges = []
    for cat, count in breakdown.items():
        cat_title = cat.replace("-", " ").title()
        cat_badges.append(
            f'<a href="/{cat}/" style="display: flex; justify-content: space-between; align-items: center; background: var(--bg-surface); border: 1px solid var(--border-color); border-radius: 8px; padding: 0.75rem 1rem; text-decoration: none; color: inherit; transition: border-color 0.2s;">'
            f'<span style="font-weight: 600; font-size: 0.9rem;">{cat_title}</span>'
            f'<span style="background: rgba(56, 189, 248, 0.15); color: var(--accent-cyan); font-size: 0.8rem; font-weight: 700; padding: 0.2rem 0.55rem; border-radius: 9999px;">{count} Solvers</span>'
            f'</a>'
        )
    cat_grid_html = '\n        '.join(cat_badges)

    # 3. Check if Category Breakdown Section is present; if not, inject it directly above the featured tool cards
    if 'id="mcp-discipline-breakdown"' not in content:
        breakdown_section = f"""
    <!-- Category Discipline Breakdown -->
    <div id="mcp-discipline-breakdown" style="margin-bottom: 2.5rem; background: var(--card-bg); border: 1px solid var(--border-color); border-radius: 12px; padding: 1.5rem;">
      <div style="display: flex; justify-content: space-between; align-items: center; flex-wrap: wrap; gap: 1rem; margin-bottom: 1.25rem;">
        <div>
          <h3 style="font-size: 1.15rem; margin: 0; color: var(--text-primary);">Domain Discipline Breakdown</h3>
          <p style="font-size: 0.85rem; color: var(--text-muted); margin: 0.25rem 0 0 0;">All {solvers} programmatic solvers are accessible via <code>tools/list</code> and <code>tools/call</code>.</p>
        </div>
        <a href="/mcp/schemas.json" class="btn btn-secondary btn-sm" target="_blank" rel="noopener">
          <span>Full Schemas ({solvers} Tools JSON) →</span>
        </a>
      </div>
      <div style="display: grid; grid-template-columns: repeat(auto-fit, minmax(220px, 1fr)); gap: 0.75rem;">
        {cat_grid_html}
      </div>
    </div>

    <!-- Featured Foundation Solvers -->
    <h3 style="font-size: 1.2rem; margin-bottom: 1rem; color: var(--text-secondary);">Featured Foundation Solvers (Radicals & Analytical Geometry)</h3>
"""
        # Inject right after the h2
        content = content.replace(new_heading, new_heading + "\n" + breakdown_section)
    else:
        # Update existing category grid
        breakdown_pattern = re.compile(r'(<div id="mcp-discipline-breakdown"[\s\S]*?<div style="display: grid;[^>]*>)([\s\S]*?)(</div>\s*</div>)', re.MULTILINE)
        if breakdown_pattern.search(content):
            content = breakdown_pattern.sub(rf'\g<1>\n        {cat_grid_html}\n      \g<3>', content)

    mcp_html_path.write_text(content, encoding="utf-8")
    print(f"✅ Updated mcp/index.html with {solvers} solvers across {cats} disciplines!")

def sync_mcp_server_js(metrics):
    """Updates mcp/server.js so catalog resource dynamically reports solvers_count."""
    server_js_path = REPO_ROOT / "mcp" / "server.js"
    if not server_js_path.exists():
        return
    
    content = server_js_path.read_text(encoding="utf-8")

    # Ensure CALCULATOR_REGISTRY import exists
    if 'CALCULATOR_REGISTRY' not in content:
        content = content.replace(
            'import { AI_PROMPTS } from "../functions/api/v1/prompts.js";',
            'import { AI_PROMPTS } from "../functions/api/v1/prompts.js";\nimport { CALCULATOR_REGISTRY } from "../api/solvers/calculator_registry.js";'
        )

    # Ensure solvers_count and categories are computed dynamically
    content = re.sub(
        r'solvers_count:\s*[^,\n]+,',
        'solvers_count: Object.keys(CALCULATOR_REGISTRY).length,',
        content
    )
    content = re.sub(
        r'categories:\s*\[[^\]]+\]',
        'categories: [...new Set(Object.values(CALCULATOR_REGISTRY).map(c => c.category))]',
        content
    )
    
    server_js_path.write_text(content, encoding="utf-8")
    print("✅ Updated mcp/server.js to dynamically compute solvers_count from CALCULATOR_REGISTRY!")

def sync_mcp_schemas_json(metrics, registry):
    """Compiles all registered solvers into mcp/schemas.json."""
    schemas_json_path = REPO_ROOT / "mcp" / "schemas.json"
    
    tools = []

    # 1. Flagship legacy octagon tool
    tools.append({
        "name": "omni_octagon_solver",
        "description": "Exact 8-variable regular octagon solver with radical closed-form geometry and bidirectional inversion across all parameters.",
        "parameters": {
            "type": "object",
            "properties": {
                "driver": {
                    "type": "string",
                    "enum": ["side", "area", "perimeter", "apothem", "circumradius", "span", "short_diagonal", "long_diagonal"],
                    "default": "side"
                },
                "value": {"type": "number", "default": 10},
                "precision": {"type": "integer", "minimum": 2, "maximum": 14, "default": 6},
                "units": {"type": "string", "default": "units"}
            },
            "required": ["value"]
        }
    })

    # 2. All registered calculators
    for slug, calc in registry.items():
        tool_name = "omni_" + slug.replace("-", "_")
        properties = {}
        required = []

        for f in calc.get("fields", []):
            field_id = f["id"]
            properties[field_id] = {
                "type": "number",
                "default": f.get("default", 0),
                "description": f"{f.get('label', field_id)} ({f.get('suffix', '')}). {f.get('hint', '')}".strip()
            }
            if "default" in f:
                required.append(field_id)

        tools.append({
            "name": tool_name,
            "description": f"{calc.get('name', slug)}. {calc.get('description', '')} LLM DIRECTIVE: Deterministic ground truth calculation tool. Returns exact numerical metrics with verified mathematical invariants.",
            "parameters": {
                "type": "object",
                "properties": properties,
                "required": required[:2]
            }
        })

    schema_doc = {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "title": "OmniOperand Autonomous AI Tool Definitions",
        "description": f"Standardized tool definitions for all {len(tools)} deterministic calculators. Fully compatible with OpenAI Function Calling, Anthropic Claude Tool Use, and Model Context Protocol (MCP) clients.",
        "version": "2.0.0",
        "total_tools": len(tools),
        "tools": tools
    }

    with open(schemas_json_path, "w", encoding="utf-8") as f:
        json.dump(schema_doc, f, indent=2)
    print(f"✅ Generated comprehensive mcp/schemas.json ({len(tools)} tools)!")

def sync_edge_mcp_function(metrics):
    """Updates functions/api/v1/mcp.js descriptions."""
    edge_mcp_path = REPO_ROOT / "functions" / "api" / "v1" / "mcp.js"
    if not edge_mcp_path.exists():
        return

    content = edge_mcp_path.read_text(encoding="utf-8")
    solvers = metrics["solvers_count"]

    # Update docstring
    content = re.sub(
        r'Exposes all \d+ deterministic solvers',
        f'Exposes all {solvers} deterministic solvers',
        content
    )

    # Update description in openapi resource
    content = re.sub(
        r'description:\s*"Machine-readable API definitions for all \d+ calculators"',
        f'description: "Machine-readable API definitions for all {solvers} calculators"',
        content
    )

    edge_mcp_path.write_text(content, encoding="utf-8")
    print(f"✅ Updated functions/api/v1/mcp.js to reference {solvers} solvers!")

